clc; clear;

%% ?????? ???????
items = [4 3 3 2 2 1];   % ????? ???????
bin_capacity = 5;          % ??? ???????
n_items = length(items);

%% ????? ??????
node_stack = {}; % ????? ????? ???????? ??????
initial_node.patterns = eye(n_items); % ?? ???? ?? ????? ?????
initial_node.constraints = [];
node_stack{end+1} = initial_node;

best_solution = inf;
best_patterns = [];

options = optimoptions('linprog','Display','none');

%% ?? ??????
while ~isempty(node_stack)
    % ?????? ?????? ??????? (DFS)
    node = node_stack{end};
    node_stack(end) = [];
    
    patterns = node.patterns;
    
    extra_constraints = node.constraints;
    
    % ????? RMP ???? ??????
    f = ones(1, size(patterns,2));
    A = -patterns;
    b = -ones(n_items,1);
    
    if ~isempty(extra_constraints)
        A = [A; extra_constraints(:,1:end-1)];
        b = [b; extra_constraints(:,end)];
    end
    
    % ?? ????????? ?????
    [y, fval, exitflag, output, lambda] = linprog(f, A, b, [], [], zeros(size(f)), [], options);
    
    if isempty(y) || fval >= best_solution
        continue; % ????? ?????? ??? ?? ?????
    end
    
    %% ????? ??????? (Pricing Problem) - ?? Knapsack ??????
    duals = lambda.ineqlin;
    new_pattern = zeros(n_items,1);
    remaining_capacity = bin_capacity;
    [~, sorted_idx] = sort(duals,'descend');
    for i = sorted_idx'
        if items(i) <= remaining_capacity
            new_pattern(i) = 1;
            remaining_capacity = remaining_capacity - items(i);
        end
    end
    rc = 1 - duals' * new_pattern;
    
    if rc < -1e-6
        % ??? ?????? ?????? ??? ??? ??????
        node.patterns = [patterns new_pattern];
        node_stack{end+1} = node;
        continue;
    end
    
    %% ???? ?? ???? ??????
    if all(abs(y - round(y)) < 1e-6)
        % ???? ????
        if sum(y) < best_solution
            best_solution = sum(y);
            best_patterns = patterns;
        end
    else
        % ???? ????: ????? ???? (Branching)
        [~, idx_frac] = max(abs(y - round(y))); % ???? ???? ???? ????
        % ???: force y(idx_frac) = 0
        cons1 = [zeros(1, size(patterns,2))]; cons1(idx_frac) = 1;
        cons1 = [cons1 0]; % last column = rhs
        node1 = node;
        node1.constraints = [node1.constraints; cons1];
        node_stack{end+1} = node1;
        % ???: force y(idx_frac) = 1
        cons2 = [zeros(1, size(patterns,2))]; cons2(idx_frac) = 1;
        cons2 = [cons2 1]; % rhs = 1
        node2 = node;
        node2.constraints = [node2.constraints; cons2];
        node_stack{end+1} = node2;
    end
end

%% ??? ????
disp('???? ?????? ???????? Branch-and-Price:');
disp(best_patterns);
disp(['??? ???????? ????????: ', num2str(best_solution)]);